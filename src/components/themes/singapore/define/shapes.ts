/**
 * 生成「∩ 形开底门框」路径（宽度可任意，竖框粗细不变）。
 *
 * 官方矢量 46.249 × 48.595：竖框厚 4.04、顶栏厚 8.664、顶角 R ≈ 3.35。
 * 直接按比例横向拉伸会把竖框拉粗（用户 2026-11-13 指出），所以这里按高度换算、
 * 横向只延长中段——`3-6` 加宽时框线粗细保持一致。
 */
export function exitDoorPath(w: number, h: number, baseH = 48.595): string {
  const k = h / baseH;
  const legT = 4.04 * k;      // 竖框厚
  const topT = 8.664 * k;     // 顶栏厚
  const r = 3.352 * k;        // 顶角
  const ri = Math.max(0, r - legT * 0.35);
  const wL = legT;            // 内洞左
  const wR = w - legT;        // 内洞右
  const outer = `M ${r} 0 H ${w - r} A ${r} ${r} 0 0 1 ${w} ${r} V ${h} H 0 V ${r} A ${r} ${r} 0 0 1 ${r} 0 Z`;
  const inner = `M ${wL} ${topT} H ${wR} V ${h} H ${wL} V ${topT} Z`;
  void ri;
  return `${outer} ${inner}`;
}

// 官方 Caplet：椭圆端胶囊（rx = 0.286h、ry = 0.5h）
export function capletPath(w: number, h: number, rxRatio = 0.286): string {
  const rx = Math.min(h * rxRatio, w / 2);
  return `M ${rx} 0 H ${w - rx} A ${rx} ${h / 2} 0 0 1 ${w - rx} ${h} H ${rx} A ${rx} ${h / 2} 0 0 1 ${rx} 0 Z`;
}

